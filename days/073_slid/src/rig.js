// rig.js — Day 073「影がすべった距離（the distance the shadow slid）」
//
// 再現元は 融点 Gallery and shop（つくば市）の FV。
// 青灰のホリゾントに白い階段状の展示台を組み、その上に手仕事のプロダクトを
// **俯瞰で1枚**に収めた物撮り。ここで再現するのは商品ではなく、
// 「真上から撮る」と決めた瞬間に画面に起きることのほうである。
//
// ── 真上（正投影）では、高さはシルエットに入らない ──
//
//   直交投影で真下を見ると、床に置いた厚さ 6mm の円盤と、
//   高さ 78mm の円柱は、**同じ円**として映る。輪郭は一致する。
//   陰影も一致する（天板の法線はどちらも (0,1,0) で、太陽も1つなので
//   明るさは 1 ピクセルも違わない）。
//
//   高さを運ぶ経路は1本しか残っていない。**影がどれだけすべったか**である。
//
//     s = h · cot θ          （θ = 太陽の仰角）
//
//   これが画面に出るすべて。だから rig には「立体」も「奥行き」も無く、
//   あるのは **平面上の footprint と、その平行移動だけ**。
//
// ── なぜホリゾント（cyclorama）なのか ──
//
//   壁と床の入隅があると、そこに1本の線が出る。線が出ると、
//   人はそれを水平線として読み、高さをそこから推定しはじめる。
//   融点の FV は地を1色のベタで塗り切っていて、線が1本も無い。
//   **奥行きの手がかりを影だけに絞るための、いちばん安い装置**である。
//   だからここでも地は #85AFD8 の1面だけで、罫も水平線も置かない。

const mm = (v) => v / 1000

