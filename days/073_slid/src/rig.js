// ── 装置そのもの ───────────────────────────────────────────────────────
// 画面に出る唯一の式。ここ以外に高さを絵にする経路は無い。
export const slide = (hMeters, thetaDeg) => hMeters / Math.tan((thetaDeg * Math.PI) / 180)

export const sunAt = (t) => {
  const theta = SUN.thetaMid + SUN.thetaAmp * Math.cos((2 * Math.PI * t) / SUN.thetaPeriod)
  const phi = SUN.phi + SUN.phiDrift * Math.sin((2 * Math.PI * t) / SUN.phiPeriod)
  const th = (theta * Math.PI) / 180
  const ph = (phi * Math.PI) / 180
  // 影の進む向き（水平面内の単位ベクトル）
  const dir = [Math.cos(ph), Math.sin(ph)]
  // 面から光源へ向かう単位ベクトル
  const L = [-dir[0] * Math.cos(th), Math.sin(th), -dir[1] * Math.cos(th)]
  return { theta, phi, dir, L, cot: 1 / Math.tan(th), sin: Math.sin(th) }
}

