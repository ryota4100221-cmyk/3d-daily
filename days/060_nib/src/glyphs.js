// 骨格を折れ線に落とす。直線は2点で足りる（曲率がないので太さ関数も線形）。
// 円弧は接線角が連続的に回るので、そこだけ細かく刻む。
export function polyline(stroke) {
  if (stroke.k === 'l') {
    return [
      [stroke.x1, stroke.y1],
      [stroke.x2, stroke.y2],
    ]
  }
  const { cx, cy, r, a0, a1 } = stroke
  const span = Math.abs(a1 - a0)
  const n = Math.max(8, Math.round(span / 4)) // 4度に1点
  const pts = []
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)])
  }
  return pts
}

// 1行ぶんの字送り。tracking は em 単位。
export function layout(text, tracking) {
  const items = []
  let x = 0
  for (const ch of text) {
    if (ch === ' ') {
      x += 0.4 + tracking
      continue
    }
    const g = GLYPHS[ch]
    if (!g) continue
    items.push({ ch, g, x })
    x += g.w + tracking
  }
  return { items, width: x - tracking }
}
